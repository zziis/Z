-- ===== المستخدمون =====
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 30),
  username text unique,
  role text not null default 'user' check (role in ('user','admin')),
  is_banned boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists role text not null default 'user';
alter table public.profiles add column if not exists is_banned boolean not null default false;

-- توليد username للحسابات القديمة التي لا تملكه
update public.profiles
set username = 'user_' || substr(replace(id::text,'-',''),1,8)
where username is null or btrim(username)='';

create unique index if not exists profiles_username_unique_idx on public.profiles(lower(username));

-- إنشاء الملف الشخصي تلقائيًا بعد التسجيل
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  base_username text;
begin
  base_username := lower(coalesce(new.raw_user_meta_data->>'username','user_' || substr(replace(new.id::text,'-',''),1,8)));
  insert into public.profiles(id,display_name,username)
  values(
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(new.email,'@',1), 'مستخدم'),
    base_username
  )
  on conflict (id) do nothing;
  return new;
exception when unique_violation then
  insert into public.profiles(id,display_name,username)
  values(new.id,coalesce(nullif(new.raw_user_meta_data->>'display_name',''),'مستخدم'),base_username || '_' || substr(replace(new.id::text,'-',''),1,4))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- دالة آمنة لمعرفة هل المستخدم مدير
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin');
$$;

-- ===== الرومات =====
create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 50),
  description text default '',
  welcome_text text default '',
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.rooms add column if not exists welcome_text text default '';

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1000),
  media_type text check (media_type is null or media_type in ('image','audio')),
  media_path text,
  media_duration integer,
  created_at timestamptz not null default now()
);
alter table public.messages add column if not exists media_type text;
alter table public.messages add column if not exists media_path text;
alter table public.messages add column if not exists media_duration integer;
create index if not exists messages_room_created_idx on public.messages(room_id,created_at);

-- ===== الرسائل الخاصة =====
create table if not exists public.private_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1000),
  media_type text check (media_type is null or media_type in ('image','audio')),
  media_path text,
  media_duration integer,
  delivered_at timestamptz,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  check (sender_id <> receiver_id)
);
alter table public.private_messages add column if not exists media_type text;
alter table public.private_messages add column if not exists media_path text;
alter table public.private_messages add column if not exists media_duration integer;
alter table public.private_messages add column if not exists delivered_at timestamptz;
create index if not exists private_messages_sender_idx on public.private_messages(sender_id,created_at desc);
create index if not exists private_messages_receiver_idx on public.private_messages(receiver_id,created_at desc);


-- ===== إيصالات قراءة رسائل الرومات =====
create table if not exists public.room_message_reads (
  message_id bigint not null references public.messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key(message_id,user_id)
);
alter table public.room_message_reads enable row level security;

DROP POLICY IF EXISTS "room_reads_select_authenticated" ON public.room_message_reads;
CREATE POLICY "room_reads_select_authenticated" ON public.room_message_reads FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "room_reads_insert_own" ON public.room_message_reads;
CREATE POLICY "room_reads_insert_own" ON public.room_message_reads FOR INSERT TO authenticated WITH CHECK (user_id=auth.uid());

-- حذف الحساب الحالي نهائيًا
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  delete from auth.users where id = auth.uid();
end;
$$;
revoke all on function public.delete_my_account() from public;
grant execute on function public.delete_my_account() to authenticated;


