  public=false,
  file_size_limit=12582912,
  allowed_mime_types=excluded.allowed_mime_types;

DROP POLICY IF EXISTS "chat_media_insert_own" ON storage.objects;
CREATE POLICY "chat_media_insert_own"
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id='chat-media'
  AND (storage.foldername(name))[2]=auth.uid()::text
);

DROP POLICY IF EXISTS "chat_media_select_authorized" ON storage.objects;
CREATE POLICY "chat_media_select_authorized"
ON storage.objects FOR SELECT TO authenticated
USING (
  bucket_id='chat-media'
  AND (
    owner_id=auth.uid()::text
    OR EXISTS (
      SELECT 1 FROM public.messages m
      WHERE m.media_path=storage.objects.name
    )
    OR EXISTS (
      SELECT 1 FROM public.private_messages pm
      WHERE pm.media_path=storage.objects.name
        AND (pm.sender_id=auth.uid() OR pm.receiver_id=auth.uid())
    )
  )
);

DROP POLICY IF EXISTS "chat_media_delete_own" ON storage.objects;
CREATE POLICY "chat_media_delete_own"
ON storage.objects FOR DELETE TO authenticated
USING (
  bucket_id='chat-media'
  AND owner_id=auth.uid()::text
);

